/**
 * App theme. `themeMode` comes from DataStore ("system" | "light" | "dark") so the user can
 * override the system appearance independently of the language setting.
 *
 * `dynamicColor` defaults to false so the indigo/teal 3DCreator brand is preserved on every
 * device; pass true to use the Android 12+ wallpaper-derived scheme instead.
 */
@Composable
fun TDCreatorTheme(
    themeMode: String = PreferencesRepository.THEME_SYSTEM,
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val systemDark = isSystemInDarkTheme()
    val dark = when (themeMode) {
        PreferencesRepository.THEME_DARK -> true
        PreferencesRepository.THEME_LIGHT -> false
        else -> systemDark
    }
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        dark -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
